-- Tenantboard: tenant tables, each created with its policies attached, so no
-- table ever exists, even briefly, without its row access and masking policies.
USE ROLE ACCOUNTADMIN;
USE DATABASE TENANTBOARD;

-- @deploy: everything below this line is database-relative.

USE SCHEMA APP;

CREATE TABLE IF NOT EXISTS MERCHANTS (
  TENANT_ID  VARCHAR(64)   NOT NULL PRIMARY KEY,
  SLUG       VARCHAR(64)   NOT NULL UNIQUE,
  NAME       VARCHAR(200)  NOT NULL,
  PLAN       VARCHAR(20)   NOT NULL,
  REGION     VARCHAR(20)   NOT NULL,
  CURRENCY   VARCHAR(3)    NOT NULL,
  CREATED_AT TIMESTAMP_NTZ NOT NULL
)
WITH ROW ACCESS POLICY TENANT_ISOLATION ON (TENANT_ID)
COMMENT = 'One row per tenant (merchant) of the platform';

CREATE TABLE IF NOT EXISTS CUSTOMERS (
  TENANT_ID   VARCHAR(64)   NOT NULL,
  CUSTOMER_ID NUMBER(10,0)  NOT NULL,
  NAME        VARCHAR(200)  NOT NULL,
  EMAIL       VARCHAR(320)  NOT NULL WITH MASKING POLICY EMAIL_MASK,
  COUNTRY     VARCHAR(2)    NOT NULL,
  CREATED_AT  TIMESTAMP_NTZ NOT NULL,
  PRIMARY KEY (TENANT_ID, CUSTOMER_ID)
)
WITH ROW ACCESS POLICY TENANT_ISOLATION ON (TENANT_ID)
COMMENT = 'A merchant''s buyers; EMAIL is PII';

-- Order ids are unique per tenant only: every merchant has an ORD-000001.
CREATE TABLE IF NOT EXISTS ORDERS (
  TENANT_ID    VARCHAR(64)   NOT NULL,
  ORDER_ID     VARCHAR(32)   NOT NULL,
  CUSTOMER_ID  NUMBER(10,0)  NOT NULL,
  ORDERED_AT   TIMESTAMP_NTZ NOT NULL,
  STATUS       VARCHAR(20)   NOT NULL,
  CHANNEL      VARCHAR(20)   NOT NULL,
  CURRENCY     VARCHAR(3)    NOT NULL,
  TOTAL_AMOUNT NUMBER(12,2)  NOT NULL,
  PRIMARY KEY (TENANT_ID, ORDER_ID)
)
WITH ROW ACCESS POLICY TENANT_ISOLATION ON (TENANT_ID)
COMMENT = 'Orders of every merchant';

CREATE TABLE IF NOT EXISTS LINE_ITEMS (
  TENANT_ID  VARCHAR(64)  NOT NULL,
  ORDER_ID   VARCHAR(32)  NOT NULL,
  LINE_NO    NUMBER(4,0)  NOT NULL,
  SKU        VARCHAR(32)  NOT NULL,
  QUANTITY   NUMBER(6,0)  NOT NULL,
  UNIT_PRICE NUMBER(12,2) NOT NULL,
  PRIMARY KEY (TENANT_ID, ORDER_ID, LINE_NO)
)
WITH ROW ACCESS POLICY TENANT_ISOLATION ON (TENANT_ID)
COMMENT = 'Order lines';
